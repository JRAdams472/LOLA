#!/usr/bin/env node
// Generates lib/field-map.ts from the backend field catalog
// (src/Lola.Domain/Applications/mismo-field-map.json — the single truth
// for validation, masking, and both MISMO mappers). Re-run after any
// catalog change: node scripts/gen-field-map.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "../../..");
const map = JSON.parse(
  readFileSync(
    join(root, "src/Lola.Domain/Applications/mismo-field-map.json"),
    "utf8",
  ),
);

const SECTION_FOR = [
  [/^party\[\d+\]\.employment/, "employment"],
  [/^party\[\d+\]/, "borrower"],
  [/^demographics\./, "borrower"],
  [/^asset\[/, "assets"],
  [/^liability\[/, "liabilities"],
  [/./, "loan"], // subject_property.*, loan.*, top-level loan fields, declaration.*
];

const LABEL_OVERRIDES = {
  ssn: "SSN",
  dob: "Date of birth",
  zip: "ZIP",
  ltv: "LTV",
  cltv: "CLTV",
  va_eligible: "VA eligible",
  est_value: "Estimated value",
  years_at: "Years at address",
};

const leaf = (path) => path.split(".").pop().replace(/\[\d+\]/g, "");
const title = (s) =>
  s
    .split("_")
    .map((w) => (w.length <= 2 ? w.toUpperCase() : w[0].toUpperCase() + w.slice(1)))
    .join(" ");

const specFor = (f) => {
  const key = leaf(f.path);
  const section = SECTION_FOR.find(([re]) => re.test(f.path))[1];
  return {
    path: f.path,
    label: LABEL_OVERRIDES[key] ?? title(key),
    type: f.type,
    enum: f.enum ?? null,
    piiClass: f.piiClass ?? null,
    required: f.required === true,
    section,
  };
};

const fields = map.fields.map(specFor);

const out = `// GENERATED by scripts/gen-field-map.mjs from
// src/Lola.Domain/Applications/mismo-field-map.json — do not edit.
// Re-run: node scripts/gen-field-map.mjs

export type FieldType = "string" | "decimal" | "int" | "date" | "bool" | "enum";
export type PiiClass =
  | "Name" | "Address" | "Contact" | "Ssn" | "Dob" | "Account" | "Income" | "Other";
export type SectionId = "borrower" | "employment" | "assets" | "liabilities" | "loan";

export interface FieldSpec {
  path: string;
  label: string;
  type: FieldType;
  enum: string[] | null;
  piiClass: PiiClass | null;
  required: boolean;
  section: SectionId;
}

export const SECTIONS: { id: SectionId; label: string }[] = [
  { id: "borrower", label: "Borrower(s)" },
  { id: "employment", label: "Employment & Income" },
  { id: "assets", label: "Assets" },
  { id: "liabilities", label: "Liabilities" },
  { id: "loan", label: "Property & Loan" },
];

export const FIELDS: FieldSpec[] = ${JSON.stringify(fields, null, 2)};

export const FIELD_MAP: Record<string, FieldSpec> = Object.fromEntries(
  FIELDS.map((f) => [f.path, f]),
);

export const fieldsFor = (section: SectionId): FieldSpec[] =>
  FIELDS.filter((f) => f.section === section);
`;

writeFileSync(join(dirname(fileURLToPath(import.meta.url)), "../lib/field-map.ts"), out);
console.log(`field-map.ts: ${fields.length} fields`);
