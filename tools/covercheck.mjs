#!/usr/bin/env node
// covercheck — per-area coverage floor for LOLA (ported from ISPPr).
//
//   node tools/covercheck.mjs <lcov.info> [-floor 80] [-goal 95]
//
// Coverage input is lcov format (*.info). .NET: coverlet emits lcov via
//   dotnet test --collect:"XPlat Code Coverage" -- DataCollectionRunSettings.DataCollectors.DataCollector.Configuration.Format=lcov
// Web: vitest/jest --coverage writes clients/<app>/coverage/lcov.info.
//
// Rules (repo policy):
//   * every "major code area" must meet -floor percent or the check fails.
//     Areas: src/<Project>/ and tests are project-granular; clients/*
//     group by directory (sibling convention);
//   * -goal is the overall target — reported, not enforced;
//   * generated files (banner "DO NOT EDIT" / "<auto-generated", *.g.cs,
//     *.designer.cs) and test files/projects are exempt;
//   * migrations/** and composition roots (Program.cs) are exempt —
//     verified by compose/e2e, not unit coverage.

import { readFileSync, existsSync } from "node:fs";
import { dirname, extname, posix } from "node:path";

const args = process.argv.slice(2);
const file = args[0];
const flag = (n, d) => {
  const i = args.indexOf(`-${n}`);
  return i === -1 ? d : Number(args[i + 1]);
};
const FLOOR = flag("floor", 80);
const GOAL = flag("goal", 95);

if (!file || !existsSync(file)) {
  console.error(`usage: covercheck <lcov.info> [-floor 80] [-goal 95]`);
  process.exit(2);
}

// Path roots that anchor a repo-relative path inside an lcov SF: record.
const ROOT_MARKERS = ["/src/", "/tests/", "/clients/"];

const SKIP_FILE = [/(\.test\.[jt]sx?|\.spec\.[jt]sx?)$/, /__tests__\//, /(^|\/)Program\.cs$/];
const SKIP_AREA = [/^tests\//, /^migrations\//, /^\.$/, /(^|\/)node_modules\//];

function isGenerated(path) {
  if (/\.(g|g\.i|designer)\.cs$/i.test(path)) return true;
  try {
    const head = readFileSync(path, "utf8").slice(0, 400);
    return head.includes("DO NOT EDIT") || head.includes("<auto-generated");
  } catch {
    return false; // source gone (CI may check paths from another dir) — don't exempt
  }
}

// lcov: "SF:<path>" ... "DA:line,hits" ... "end_of_record"
function parseLcov(text) {
  const files = new Map();
  let cur = null;
  for (const raw of text.split("\n")) {
    const line = raw.trim();
    if (line.startsWith("SF:")) {
      let p = line.slice(3).replaceAll("\\", "/");
      // Strip any absolute/tooling prefix — keep repo-relative tail.
      for (const marker of ROOT_MARKERS) {
        const i = p.lastIndexOf(marker);
        if (i !== -1) { p = p.slice(i + 1); break; }
      }
      cur = [0, 0];
      files.set(p, cur);
    } else if (line.startsWith("DA:") && cur) {
      const hits = Number(line.slice(3).split(",")[1]);
      cur[1]++;
      if (hits > 0) cur[0]++;
    }
  }
  return files;
}

// Area granularity: src/<Project> groups at project level; everything
// else groups by directory (clients/* per sibling convention).
function areaOf(path) {
  if (path.startsWith("src/") || path.startsWith("tests/")) {
    const segs = path.split("/");
    return segs.slice(0, 2).join("/");
  }
  return posix.dirname(path);
}

const files = parseLcov(readFileSync(file, "utf8"));

const areas = new Map(); // area -> [covered, total]
for (const [path, [cov, tot]] of files) {
  if (SKIP_FILE.some((r) => r.test(path)) || isGenerated(path)) continue;
  const area = areaOf(path);
  if (SKIP_AREA.some((r) => r.test(area))) continue;
  const [c, t] = areas.get(area) ?? [0, 0];
  areas.set(area, [c + cov, t + tot]);
}

console.log(`\ncovercheck — floor ${FLOOR}%/area, goal ${GOAL}% overall\n`);
let fail = false;
let sumC = 0, sumT = 0;
for (const [area, [c, t]] of [...areas].sort((a, b) => a[0].localeCompare(b[0]))) {
  const pct = t ? (100 * c) / t : 100;
  sumC += c; sumT += t;
  const mark = pct < FLOOR ? "FAIL" : " ok ";
  if (pct < FLOOR) fail = true;
  console.log(` ${mark}  ${area.padEnd(32)} ${pct.toFixed(1).padStart(5)}%  (${c}/${t} lines)`);
}
const overall = sumT ? (100 * sumC) / sumT : 100;
console.log(`\n overall: ${overall.toFixed(1)}%  (goal ${GOAL}%)`);
if (overall < GOAL) console.log(` note: overall below ${GOAL}% goal — directional, not a hard gate`);
process.exit(fail ? 1 : 0);
